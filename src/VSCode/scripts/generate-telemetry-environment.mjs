// generate-telemetry-environment.mjs — writes src/generated/telemetryEnvironment.ts (gitignored),
// which tells the extension which built-in Application Insights resource this build reports to
// (issue #1160). Runs from the `precompile` / `prewatch` npm hooks, so `npm run compile`,
// `vsce package` (via vscode:prepublish) and the test build all pick it up.
//
//   REQNROLL_TELEMETRY_ENV=prod npm run compile    # release build -> production resource
//   npm run compile                                # anything else -> dev resource (default)
//
// A prod build refuses to proceed while the prod connection string is still a TODO placeholder.

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const requested = (process.env.REQNROLL_TELEMETRY_ENV ?? '').trim().toLowerCase() || 'dev';
if (requested !== 'dev' && requested !== 'prod') {
  console.error(`REQNROLL_TELEMETRY_ENV must be 'dev' or 'prod' (was '${requested}').`);
  process.exit(1);
}

if (requested === 'prod') {
  const source = readFileSync('src/telemetryConnections.ts', 'utf8');
  const prod = /PROD_CONNECTION_STRING =\s*'([^']*)'/.exec(source)?.[1] ?? '';
  if (!prod || prod.includes('TODO')) {
    console.error(
      'src/telemetryConnections.ts: PROD_CONNECTION_STRING is still a placeholder; paste the real ' +
        'Application Insights connection string before a prod build.',
    );
    process.exit(1);
  }
}

mkdirSync('src/generated', { recursive: true });
writeFileSync(
  'src/generated/telemetryEnvironment.ts',
  `// Generated by scripts/generate-telemetry-environment.mjs. Do not edit; not committed.\n` +
    `import type { TelemetryEnvironment } from '../telemetryConnections';\n\n` +
    `export const TELEMETRY_ENVIRONMENT: TelemetryEnvironment = '${requested}';\n`,
);
console.log(`Telemetry environment: ${requested}`);
